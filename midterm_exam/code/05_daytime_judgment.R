# ① 시간대 묶음별 비 온 날 차이율(평일)
band_of <- function(h) case_when(h <= 6 ~ "1 새벽(05~06시)", h <= 8 ~ "2 출근(07~08시)",
                                 h <= 15 ~ "3 낮(09~15시)", h == 16 ~ "4 오후(16시)",
                                 h <= 18 ~ "5 퇴근(17~18시)", h <= 21 ~ "6 저녁(19~21시)",
                                 TRUE ~ "7 늦은 밤(22시~)")
rain_hourly %>%
  group_by(묶음 = band_of(시), 비) %>%
  summarise(승차 = sum(평균승차), .groups = "drop_last") %>%
  summarise(차이율 = (승차[비] / 승차[!비] - 1) * 100)

