# ④ 6장 세 번째 시도(평일 비 온 날 ÷ 안 온 날 − 1)를 범위별로 다시 계산
weekday_daily <- subway_long %>%
  filter(구분 == "승차", !wday(날짜) %in% c(1, 7)) %>%
  group_by(날짜, 비) %>%
  summarise(하루 = sum(인원),
            일과_09_15 = sum(인원[시 %in% 9:15]),
            일과_10_14 = sum(인원[시 %in% 10:14]),
            .groups = "drop")
nrow(weekday_daily)   # 평일 261일

weekday_daily %>%
  group_by(비) %>%
  summarise(across(c(하루, 일과_09_15, 일과_10_14), mean)) %>%
  summarise(across(c(하루, 일과_09_15, 일과_10_14), ~ (.x[비] / .x[!비] - 1) * 100))

