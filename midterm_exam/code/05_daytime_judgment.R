# 결론: 그림과 숫자는 "날씨의 영향은 일과시간(09~15시)에서 봐야 한다"는 주장을 뒷받침하지 않는다.
#   비 온 평일의 감소율은 낮(-5.4%)이 출퇴근(-5.3%, -5.2%)이나 하루 전체(-5.4%)와 거의 같고,
#   일과시간만 다시 계산해도 차이가 커지지 않았다(-5.3%). 가장 크게 준 때는 늦은 밤이었다.
#
# ① 시간대별 변화와 타는 이유
#   새벽(05~06시) -5.0%, 출근(07~08시) -5.3%, 퇴근(17~18시) -5.2%, 늦은 밤(22시~) -6.1%, 낮(09~15시) -5.4%.
#   새벽과 출퇴근은 출근·등교·업무처럼 날씨와 상관없이 해야 하는 이동이 대부분이라 줄어든 폭이 작다.
#   늦은 밤은 모임·여가 뒤 귀가처럼 미루거나 취소할 수 있는 이동이 섞여 있어 가장 많이 줄었다(24시이후 -8.3%).
#   낮에도 선택적 외출(쇼핑·병원·약속)이 있지만 업무 이동이 함께 섞여 있어 출퇴근과 비슷하게 줄었다.
#
# ② 출퇴근 비율과 희석
#   출근(07~08시) 17.2% + 퇴근(17~18시) 20.8% = 하루 합계의 약 38%. 낮(09~15시)은 31.6%다.
#   출퇴근 비중이 크면, 낮 시간대만 크게 줄어도 하루 합계에서는 그 변화가 약 3분의 1 크기로 묽어져 보인다.
#   이 희석 논리 자체는 맞지만, 실제로는 낮이 출퇴근보다 더 줄지 않았으므로 희석될 "숨은 큰 변화"가 없었다.
